enum Colormap: String {
    case greenRed
    case yellowBlue

    /// 256 级 RGB LUT（768 字节/个），编译期常量，查表零计算
    var lut: [UInt8] {
        switch self {
        case .greenRed:   return Colormap.greenRedLUT
        case .yellowBlue: return Colormap.yellowBlueLUT
        }
    }

    /// t ∈ [0,1] → RGB
    @inline(__always)
    func rgb(_ t: Float) -> (UInt8, UInt8, UInt8) {
        let lut = self.lut
        let idx = max(0, min(255, Int(t * 255.0 + 0.5))) * 3
        return (lut[idx], lut[idx + 1], lut[idx + 2])
    }

    /// 归一化值数组 → RGBA 字节流（供 GPU 顶点属性直接使用）。
    /// 大数组按核数分块并行查表（各线程写独立区间，无锁）。
    static func colorize(_ t: [Float], map: Colormap, alpha: UInt8 = 230) -> [UInt8] {
        let n = t.count
        var out = [UInt8](repeating: 0, count: n * 4)
        guard n > 0 else { return out }
        let lut = map.lut
        let chunks = n > 200_000 ? max(1, ProcessInfo.processInfo.activeProcessorCount) : 1
        out.withUnsafeMutableBufferPointer { buf in
            t.withUnsafeBufferPointer { tp in
                lut.withUnsafeBufferPointer { l in
                    let outBase = buf.baseAddress!
                    let tBase = tp.baseAddress!
                    let lutBase = l.baseAddress!
                    DispatchQueue.concurrentPerform(iterations: chunks) { ci in
                        let a = ci * n / chunks
                        let b = (ci + 1) * n / chunks
                        for i in a..<b {
                            let raw = Int(tBase[i] * 255.0 + 0.5)
                            let idx = (raw < 0 ? 0 : (raw > 255 ? 255 : raw)) * 3
                            let o = i * 4
                            outBase[o]     = lutBase[idx]
                            outBase[o + 1] = lutBase[idx + 1]
                            outBase[o + 2] = lutBase[idx + 2]
                            outBase[o + 3] = alpha
                        }
                    }
                }
            }
        }
        return out
    }

    /// SwiftUI 图例渐变（16 个采样点）
    var gradientStops: [Gradient.Stop] {
        let lut = self.lut
        return (0..<16).map { i in
            let t = Double(i) / 15.0
            let idx = min(255, Int(t * 255.0 + 0.5)) * 3
            return Gradient.Stop(
                color: Color(red: Double(lut[idx]) / 255.0,
                             green: Double(lut[idx + 1]) / 255.0,
                             blue: Double(lut[idx + 2]) / 255.0),
                location: t)
        }
    }

