//  顺序色标（256 级 RGB LUT，matplotlib 精确采样）：
//  - greenRed：绿 → 黄 → 红（RdYlGn 反向）。速度=慢绿快红，时间=早绿晚红。
//  - yellowBlue：黄 → 绿 → 青 → 蓝（viridis 子区间反向，感知均匀）。海拔=低黄高蓝。
