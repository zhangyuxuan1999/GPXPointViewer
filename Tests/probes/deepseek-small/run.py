#!/usr/bin/env python3
"""Offline N25/N28 probe: extract current product snippets and execute once."""
from __future__ import annotations

import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import time
from datetime import datetime, timezone
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
SOURCE = REPO / "GPXPointViewer/RoadNetwork.swift"
MAIN_SWIFT = Path(__file__).with_name("main.swift")
RUN_PY = Path(__file__).resolve()


def save_json(path: Path, value: dict) -> None:
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def extract(source: str) -> tuple[dict, str]:
    lines = source.splitlines()
    status = [(i, line.strip()) for i, line in enumerate(lines)
              if line.strip().startswith("return .status(") and "err.prefix(60)" in line]
    paths = [(i, line.strip()) for i, line in enumerate(lines)
             if line.strip() == "let path = ids.compactMap { coord[$0] }"]
    if len(status) != 1 or len(paths) != 1:
        raise ValueError("expected one Valhalla status expression and one rail reconstruction")
    status_line, status_text = status[0]
    if not status_text.endswith(")"):
        raise ValueError("Valhalla status expression must be on one complete line")
    expression = status_text[len("return .status("):-1]
    path_line, path_text = paths[0]
    guard_line = next((i for i in range(path_line + 1, len(lines)) if lines[i].strip()), None)
    guard_text = lines[guard_line].strip() if guard_line is not None else ""
    if not guard_text.startswith("guard ") or not guard_text.endswith("{ throw RouteError.noRailPath }"):
        raise ValueError("expected the production rail guard immediately after reconstruction")
    extraction = {
        "valhalla": {"line_1based": status_line + 1, "expression": expression},
        "rail": {"line_1based": path_line + 1, "rail_line": path_text,
                 "guard_line_1based": guard_line + 1, "guard_line": guard_text},
    }
    support = "\n".join([
        "// AUTO-GENERATED by Tests/probes/deepseek-small/run.py",
        "// The two production snippets below are extracted verbatim from GPXPointViewer/RoadNetwork.swift.",
        "import Foundation", "", "enum RouteError: Error {", "    case noRailPath", "}", "",
        "func valhallaStatus(_ ec: Int, _ err: String) -> String {", "    return " + expression, "}", "",
        "func railPathExcerpt(ids: [Int], coord: [Int: Int]) throws -> [Int] {",
        "    " + path_text, "    " + guard_text, "    return path", "}", "",
    ])
    return extraction, support


def execute(label: str, argv: list[str], evidence: Path, env: dict, timeout: int) -> dict:
    command = {"argv": argv, "cwd": str(evidence),
               "started_utc": datetime.now(timezone.utc).isoformat()}
    save_json(evidence / f"{label}-command.json", command)
    started = time.monotonic()
    result = dict(command, timed_out=False)
    try:
        cp = subprocess.run(argv, cwd=str(evidence), env=env, stdin=subprocess.DEVNULL,
                            stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=timeout)
        stdout, stderr = cp.stdout, cp.stderr
        result["exit_code"] = cp.returncode
    except subprocess.TimeoutExpired as error:
        stdout, stderr = error.stdout or b"", error.stderr or b""
        result.update(exit_code=124, timed_out=True)
    except OSError as error:
        stdout, stderr = b"", str(error).encode("utf-8")
        result.update(exit_code=127, launch_error=type(error).__name__)
    result["duration_s"] = time.monotonic() - started
    (evidence / f"{label}.stdout").write_bytes(stdout)
    (evidence / f"{label}.stderr").write_bytes(stderr)
    save_json(evidence / f"{label}-result.json", result)
    sys.stdout.write(stdout.decode("utf-8", "replace"))
    sys.stderr.write(stderr.decode("utf-8", "replace"))
    return dict(result, stdout=stdout.decode("utf-8", "replace"))


def main(argv: list[str] | None = None) -> int:
    argv = sys.argv[1:] if argv is None else argv
    if len(argv) != 1:
        print("usage: run.py <evidence-parent-dir>", file=sys.stderr)
        return 64
    parent = Path(argv[0]).resolve()
    parent.mkdir(parents=True, exist_ok=True)
    prefix = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S.%fZ_")
    evidence = Path(tempfile.mkdtemp(prefix=prefix, dir=parent))
    print(f"Evidence: {evidence}", flush=True)
    report = {"ok": False, "evidence_dir": str(evidence), "stages": {},
              "note": "One execution only; report repair must reuse saved stage logs."}
    exit_code = 2
    try:
        inputs = {"product": SOURCE, "main": MAIN_SWIFT, "runner": RUN_PY}
        contents = {label: path.read_bytes() for label, path in inputs.items()}
        report["sources"] = {label: {"path": str(path), "sha256": hashlib.sha256(contents[label]).hexdigest()}
                             for label, path in inputs.items()}
        extraction, support = extract(contents["product"].decode("utf-8"))
        save_json(evidence / "source-hashes.json", report["sources"])
        save_json(evidence / "extraction.json", extraction)
        support_path = evidence / "extracted-support.swift"
        support_path.write_text(support, encoding="utf-8")
        main_path = evidence / "main.swift"
        main_path.write_bytes(contents["main"])
        cache, tmp = evidence / "module-cache", evidence / "tmp"
        cache.mkdir()
        tmp.mkdir()
        env = os.environ.copy()
        env.update(TMPDIR=str(tmp) + os.sep, SWIFT_MODULE_CACHE_PATH=str(cache),
                   CLANG_MODULE_CACHE_PATH=str(cache))
        binary = evidence / "deepseek-small-probe"
        command = [shutil.which("xcrun") or "/usr/bin/xcrun", "swiftc", "-swift-version", "5",
                   "-module-cache-path", str(cache), "-Xcc", f"-fmodules-cache-path={cache}",
                   "-o", str(binary), str(main_path), str(support_path)]
        compiled = execute("compile", command, evidence, env, 180)
        report["stages"]["compile"] = {k: v for k, v in compiled.items() if k != "stdout"}
        exit_code = compiled["exit_code"]
        if exit_code == 0:
            ran = execute("run", [str(binary)], evidence, env, 60)
            exit_code = ran["exit_code"]
            report["stages"]["run"] = {k: v for k, v in ran.items() if k != "stdout"}
            summaries = re.findall(r"^RESULT passed=(\d+) failed=(\d+)$", ran["stdout"], re.M)
            if len(summaries) != 1:
                raise ValueError("probe must emit exactly one RESULT line; inspect run.stdout without rerunning")
            passed, failed = map(int, summaries[0])
            observed_passed = len(re.findall(r"^PASS ", ran["stdout"], re.M))
            observed_failed = len(re.findall(r"^FAIL ", ran["stdout"], re.M))
            report["probe_result"] = {"passed": passed, "failed": failed,
                                      "observed_passed": observed_passed, "observed_failed": observed_failed}
            if (passed, failed) != (observed_passed, observed_failed):
                raise ValueError("RESULT disagrees with saved PASS/FAIL lines; inspect logs without rerunning")
            report["ok"] = ran["exit_code"] == 0 and passed > 0 and failed == 0
            exit_code = ran["exit_code"] or (0 if report["ok"] else 1)
    except Exception as error:
        report["error"] = f"{type(error).__name__}: {error}"
        print(report["error"], file=sys.stderr)
        exit_code = exit_code or 2
    # Each stage is already saved separately. A summary write failure never
    # retries compilation or execution and does not destroy successful logs.
    save_json(evidence / "report.json", report)
    return exit_code if exit_code >= 0 else 1


if __name__ == "__main__":
    sys.exit(main())
